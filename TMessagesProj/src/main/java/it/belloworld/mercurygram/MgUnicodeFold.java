    // The table parsed once into two parallel arrays, the keys ascending, so a lookup is a binary
    // search with no boxing on the miss path - which is what almost every character is, and
    // getTranslitString runs per keystroke over every dialog name and over every message indexed
    // for search. KEYS is package-private so the test can check the table's shape without walking
    // the whole codepoint space.
    static final int[] KEYS;
    private static final String[] VALUES;

    static {
        final int len = FOLD_PAIRS.length();
        int count = 0;
        for (int i = 0; i < len; ) {
            final int cp = FOLD_PAIRS.codePointAt(i);
            i += Character.charCount(cp);
            // a key is what starts an entry, the ASCII after it is the value
            if (cp >= 0x80) {
                count++;
            }
        }
        KEYS = new int[count];
        VALUES = new String[count];
        int entry = 0;
        for (int i = 0; i < len; ) {
            final int cp = FOLD_PAIRS.codePointAt(i);
            i += Character.charCount(cp);
            final int valueStart = i;
            while (i < len && FOLD_PAIRS.charAt(i) < 0x80) {
                i++;
            }
            KEYS[entry] = cp;
            VALUES[entry] = FOLD_PAIRS.substring(valueStart, i);
            entry++;
        }
    }

    /**
     * Returns {@code src} normalized for local search: every decorated codepoint replaced by the
     * plain lowercase ASCII it stands for, every combining mark dropped and every symbol turned
     * into a space (see {@link #undecorate}). Plain characters, and characters from scripts we
     * have no mapping for, are returned untouched - case included, so ASCII text comes back
     * identical and the very same instance is returned when nothing needed folding.
     *
     * The result is meant for matching, never for display: it is what search compares against,
     * not a transliteration of the name.
     */
    public static String fold(String src) {
        StringBuilder dst = null;
        final int len = src.length();
        for (int i = 0; i < len; ) {
            final int cp = src.codePointAt(i);
            String replacement = null;
            // Below the first key there is nothing to look up and nothing to undecorate either,
            // and that is what almost every character of a name is.
            if (cp >= KEYS[0]) {
                final int entry = Arrays.binarySearch(KEYS, cp);
                replacement = entry >= 0 ? VALUES[entry] : undecorate(cp);
            }
            if (replacement == null) {
                if (dst != null) {
                    dst.appendCodePoint(cp);
                }
            } else {
                if (dst == null) {
                    dst = new StringBuilder(len).append(src, 0, i);
                }
                dst.append(replacement);
            }
            i += Character.charCount(cp);
        }
        return dst == null ? src : dst.toString();
    }

    /**
     * What a codepoint the table has no entry for becomes, or null to keep it as it is.
     *
     * A combining mark is decoration wherever it sits - the table drops the ones its own values
     * carried for the same reason - so it is dropped rather than left to separate a word from the
     * query that should have matched it.
     *
     * A symbol becomes a space, because local search only ever matches a query at the start of a
     * word: MessagesStorage.localSearch tests startsWith(query) and contains(" " + query). A name
     * decorated as "♥️cucina❤️italiana" has the emoji glued straight onto the word, so without a
     * separator the only reachable word would be the first one, and that one starts with the emoji.
     * This only ever affects the transliterated copy the search compares against, never what the
     * user sees.
     */
    static String undecorate(int cp) {
        switch (Character.getType(cp)) {
            case Character.NON_SPACING_MARK:
            case Character.ENCLOSING_MARK:
            case Character.FORMAT:
                return "";
            case Character.MATH_SYMBOL:
            case Character.CURRENCY_SYMBOL:
            case Character.MODIFIER_SYMBOL:
            case Character.OTHER_SYMBOL:
                return " ";
            default:
                return null;
        }
    }
